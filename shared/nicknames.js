const ALL_NICKNAMES = [
  ...ADJECTIVES.flatMap(([masculine]) => MASCULINE_ANIMALS.map((animal) => `${masculine} ${animal}`)),
  ...ADJECTIVES.flatMap(([, feminine]) => FEMININE_ANIMALS.map((animal) => `${feminine} ${animal}`)),
];
const KNOWN = new Set(ALL_NICKNAMES);

export function isGeneratedNickname(name) {
  return KNOWN.has(stripSuffix(name)) && name === name.trim();
}

// Случайный позывной, которого нет среди занятых (сравнение без учета регистра).
export function generateNickname(isTaken, exclude = '') {
  const unavailable = (name) => isTaken(name) || name === exclude;

  for (let attempt = 0; attempt < 50; attempt += 1) {
    const name = ALL_NICKNAMES[randomInt(ALL_NICKNAMES.length)];
    if (!unavailable(name)) return name;
  }

  // Словарь почти исчерпан — ищем оставшиеся варианты перебором.
  const free = ALL_NICKNAMES.filter((name) => !unavailable(name));
  if (free.length > 0) return free[randomInt(free.length)];

  // Все ~2500 сочетаний заняты — добавляем номер.
  for (let suffix = 2; ; suffix += 1) {
    const name = `${ALL_NICKNAMES[randomInt(ALL_NICKNAMES.length)]} ${suffix}`;
    if (!unavailable(name)) return name;
  }
}

// Равномерное случайное число 0..max-1; crypto.getRandomValues есть и в браузере, и в Node 20+.
export function randomInt(max) {
  const buffer = new Uint32Array(1);
  const limit = Math.floor(0x100000000 / max) * max;
  do {
    globalThis.crypto.getRandomValues(buffer);
  } while (buffer[0] >= limit);
  return buffer[0] % max;
}

function stripSuffix(name) {
  return String(name).replace(/ \d+$/, '');
}
