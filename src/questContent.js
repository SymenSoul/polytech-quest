export function reviewFor(moduleId, levelId) {
  return forLevel(REVIEW, moduleId, levelId);
}

function forLevel(table, moduleId, levelId) {
  const item = table[moduleId] ?? {};
  return item[levelId] ?? item.senior;
}

export function storyFor(moduleId, levelId) {
  return forLevel(STORY, moduleId, levelId);
}

export function hintsFor(moduleId, levelId) {
  return forLevel(HINTS, moduleId, levelId) ?? [];
}

export function glossaryFor(moduleId, levelId) {
  return forLevel(GLOSSARY, moduleId, levelId) ?? [];
}

export function byLevel(table, levelId) {
  return table[levelId] ?? table.senior;
}
